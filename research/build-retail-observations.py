"""Export comparable, already researched consumer offers for storefront SKUs."""
import json
import re
import subprocess
from collections import defaultdict
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
catalog = json.loads(subprocess.run(
    ['node', '--experimental-default-type=module', '-e',
     "import('./data.js').then(({catalogProducts})=>console.log(JSON.stringify(catalogProducts.flatMap(p=>(p.variants?.length?p.variants:[p]).map(v=>({id:v.id,productId:p.id,recipeId:p.researchRecipeId,weightKg:v.packageWeightKg,label:v.label,ean:v.ean,price:v.price,priceStatus:v.priceStatus}))))))"],
    cwd=ROOT, check=True, capture_output=True, text=True,
).stdout)

food = defaultdict(list)
for name in ('dry-cat-food', 'wet-cat-food'):
    data = json.loads((ROOT / 'research' / name / 'retail-prices.json').read_text())
    for sku in data['skus']:
        for offer in sku.get('offers', []):
            if not offer.get('priceEUR') or offer.get('availability') != 'InStock' or offer.get('supersededByLiveOffer'):
                continue
            quantity = offer.get('quantity', 1)
            if not isinstance(quantity, int) or quantity < 1:
                continue
            food[(sku['recipeId'], sku['grams'], quantity)].append(offer)

leonardo = {
    row['variantId']: [row['manufacturerOffer'], *row['competitorOffers']]
    for row in json.loads((ROOT / 'research/leonardo-dry-retail-2026-10-17.json').read_text())['items']
}

def compact(offer):
    return {
        'retailer': offer['retailer'],
        'amount': offer['priceEUR'],
        'url': offer['sourceUrl'],
        'checkedAt': offer.get('checkedAt') or offer.get('checkedOn'),
        'taxIncluded': True,
        'shippingIncluded': False,
    }

result = {}
for variant in catalog:
    if not isinstance(variant.get('price'), (int, float)) or variant.get('priceStatus') == 'pending':
        continue
    vid = variant['id']
    if vid in leonardo:
        offers = [compact(offer) for offer in leonardo[vid]]
    elif variant.get('recipeId') and variant.get('weightKg'):
        label = variant.get('label') or ''
        match = re.match(r'^\s*(\d+)\s*[x×]\s*', label)
        quantity = int(match.group(1)) if match else 1
        total_grams = round(variant['weightKg'] * 1000)
        offers = [compact(offer) for offer in food[(variant['recipeId'], total_grams // quantity, quantity)]] if total_grams % quantity == 0 else []
    else:
        offers = []
    # A retailer's latest checked exact-pack offer supersedes its earlier snapshots
    latest = {}
    for offer in offers:
        key = offer['retailer'].casefold()
        if key not in latest or (offer['checkedAt'] or '') >= (latest[key]['checkedAt'] or ''):
            latest[key] = offer
    if latest:
        result[vid] = sorted(latest.values(), key=lambda o: (o['amount'], o['retailer']))

target = ROOT / 'retail-observations.js'
target.write_text('// Generated by research/build-retail-observations.py from saved exact-pack retail research\n'
                  'export const retailObservations = ' + json.dumps(result, ensure_ascii=False, indent=2) + ';\n')
print(f'Built observations for {len(result)} catalog variants')
